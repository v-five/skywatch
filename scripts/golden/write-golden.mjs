// Turns print-golden's output into claude-code/tests/support/golden.ts, one line per key.
import { readFileSync, writeFileSync } from 'node:fs'

const [outputFile, goldenFile, ref] = process.argv.slice(2)
const match = readFileSync(outputFile, 'utf8').match(/GOLDEN>>>([\s\S]*?)<<<GOLDEN/)
if (!match) throw new Error(`no golden output in ${outputFile}`)

const golden = JSON.parse(match[1])
// JSON has no Infinity: the last hazard step's bound reads as 1e9.
for (const hazard of golden.hazardOf) if (hazard.upTo === null) hazard.upTo = 1e9

const lines = Object.entries(golden).map(([key, value]) => `  ${key}: ${JSON.stringify(value)},`)
const header = `// Generated by scripts/golden.sh from the pre-refactor code (${ref}) for the inputs in corpus/. Do not edit by hand.`
writeFileSync(goldenFile, `${header}\nexport const GOLDEN = {\n${lines.join('\n')}\n} as const\n`)
